#!/usr/bin/env python3
"""Summarize spec/output/mc-*.log into spec/model-checking-summary.md (+ .json)."""
import re, glob, os, json
root = os.path.dirname(os.path.abspath(__file__)) + "/.."
rows = []
for log in sorted(glob.glob(root + "/spec/output/mc-*.log")):
    if any(k in log for k in ("superseded", "stopped", "discarded")): continue
    label = os.path.basename(log)[3:-4]
    t = open(log).read()
    cmd = re.search(r"^COMMAND: (.*)$", t, re.M)
    cfg = re.search(r"-config (\S+)", cmd.group(1)) if cmd else None
    mode = "simulation" if "-simulate" in (cmd.group(1) if cmd else "") else "BFS"
    viol = sorted(set(re.findall(r"Error: (?:Invariant|Action property) (\w+) is violated", t)))
    nviol = len(re.findall(r"Error: (?:Invariant|Action property) \w+ is violated", t))
    fin = re.findall(r"([\d,]+) states generated, ([\d,]+) distinct states found, ([\d,]+) states left on queue", t)
    sim = re.findall(r"([\d,]+) states checked|The number of states generated: ([\d,]+)", t)
    depth = re.search(r"The depth of the complete state graph search is (\d+)", t)
    prog = re.findall(r"Progress\((\d+)\) at \S+ \S+: ([\d,]+) states generated \([^)]*\), ([\d,]+) distinct states found \([^)]*\), ([\d,]+) states left on queue", t)
    simprog = re.findall(r"Progress: ([\d,]+) states checked, ([\d,]+) traces generated", t)
    exitc = re.search(r"^EXIT: (\d+)", t, re.M)
    completed = "Model checking completed" in t
    gen = dist = queue = None
    if fin: gen, dist, queue = fin[-1]
    elif prog: _, gen, dist, queue = prog[-1]
    maxlvl = prog[-1][0] if prog else (depth.group(1) if depth else None)
    if mode == "simulation":
        ck = simprog[-1] if simprog else None
        status = ("VIOLATION" if viol else "LIMITED_COVERAGE (simulation budget)")
        cover = "%s states checked, %s traces" % ck if ck else "see log"
    else:
        exhaustive = completed and queue is not None and queue.replace(",", "") == "0" and not viol
        if exitc is None and "Finished in" not in t: status = "RUNNING"
        elif viol and not completed: status = "VIOLATION (stopped at first)"
        elif viol: status = "VIOLATION(S) + %s" % ("exhausted" if queue and queue.replace(",","")=="0" else "LIMITED_COVERAGE (budget)")
        elif exhaustive: status = "EXHAUSTED, no violation (within bounds)"
        else: status = "LIMITED_COVERAGE (budget), no violation"
        cover = "%s generated, %s distinct, queue %s, depth %s" % (gen, dist, queue, depth.group(1) if depth else maxlvl)
    rows.append(dict(label=label, cfg=cfg.group(1) if cfg else "?", mode=mode, status=status,
                     violations=viol, violation_reports=nviol, coverage=cover,
                     exit=exitc.group(1) if exitc else "running", log="spec/output/" + os.path.basename(log)))
md = ["# Model-checking summary (generated by harness/summarize-mc.py)", "",
      "Budget-terminated runs are LIMITED_COVERAGE, never exhaustive or proof. Canary violations are expected witnesses.", "",
      "| Run | Config | Mode | Outcome | Violated properties (reports) | Coverage | Log |", "|---|---|---|---|---|---|---|"]
for r in rows:
    md.append("| %s | %s | %s | %s | %s | %s | `%s` |" % (r["label"], r["cfg"], r["mode"], r["status"],
              (", ".join(r["violations"]) + " (%d)" % r["violation_reports"]) if r["violations"] else "—", r["coverage"], r["log"]))
open(root + "/spec/model-checking-summary.md", "w").write("\n".join(md) + "\n")
json.dump(rows, open(root + "/spec/model-checking-summary.json", "w"), indent=1)
print("\n".join(md))
