#!/usr/bin/env python3
"""Create a continuation hunt that starts from a TLC-reached state.
usage: make_witness_hunt.py <tlc.log> <state#> <out-module-name> <cfg> <MaxEpoch> <Txn-count>
The state must come from a counterexample of UpdateFullSpec/UpdateFocusedSpec
(reached from UInit); concatenating that prefix with any behavior explored
from WInit under MCNext gives a behavior of the full update spec."""
import re, sys
log, n, mod, cfg, maxep, ntx = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4], int(sys.argv[5]), int(sys.argv[6])
text = open(log).read()
m = re.search(r"^State %d:.*?\n(.*?)(?=^State \d+:|\n\n)" % n, text, re.S | re.M)
body = m.group(1)
st = {}
for p in re.split(r"^/\\ ", body, flags=re.M):
    p = p.strip()
    if p:
        k, v = p.split(" = ", 1); st[k.strip()] = " ".join(v.split())
def sub(v):
    v = re.sub(r"\bs(\d)\b", r"S\1", v)
    v = re.sub(r"\bt(\d)\b", r"T\1", v)
    return v
txns = ["T%d" % i for i in range(1, ntx + 1)]
for k in st:
    st[k] = sub(st[k])
for k, dflt in (("acked", "{}"), ("commitCertified", "FALSE")):
    for t in txns:
        if t + " :>" not in st[k]:
            st[k] = "(%s @@ %s :> %s)" % (st[k], t, dflt)
for e in range(0, maxep + 1):
    if not re.search(r"(\(|@@ )%d :>" % e, st["leadersByEpoch"]):
        st["leadersByEpoch"] = "(%s @@ %d :> {})" % (st["leadersByEpoch"], e)
init = "\n    /\\ ".join("%s = %s" % (k, v) for k, v in sorted(st.items()))
out = f"""---- MODULE {mod} ----
\\* Generated by make_witness_hunt.py from {log} state {n}.
\\* Continuation hunt from a TLC-reached state (see module comment in the
\\* generator): every explored behavior extends a real UpdateFullSpec prefix.
EXTENDS Update
CONSTANTS S1, S2, S3, {", ".join(txns)}
WInit ==
    /\\ {init}
WSpec == WInit /\\ [][MCNext /\\ UpdateMonitor]_uVars
====
"""
open(mod + ".tla", "w").write(out)
tconsts = "".join("    T%d = t%d\n" % (i, i) for i in range(1, ntx + 1))
c = f"""SPECIFICATION WSpec

CONSTANTS
    Server = {{s1, s2, s3}}
    Txn = {{{", ".join("t%d" % i for i in range(1, ntx + 1))}}}
    S1 = s1
    S2 = s2
    S3 = s3
{tconsts}    MaxEpoch = {maxep}
    Nil = Nil
    MaxCrash = 1
    MaxDrop = 0
    MaxSnapshot = 0

CHECK_DEADLOCK FALSE

INVARIANTS
    TypeOK
    MCTypeOK
    UTypeOK
    ElectionSafety
    OneActiveLeaderPerEpoch
    CommittedHistoriesPrefix
    ApplyRequiresCommitCertificate
    PipelinePrefix
    EpochHistoryConsistency
    SyncCompletionJustified
    CommittedNeverLostByLeader
    NewLeaderAckAfterLogging
"""
open(cfg, "w").write(c)
print("wrote", mod, cfg)
