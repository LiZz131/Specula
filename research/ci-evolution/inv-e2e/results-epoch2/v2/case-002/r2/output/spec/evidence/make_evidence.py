#!/usr/bin/env python3
"""Build and run one-state TLC evaluations for spec/invariant-evidence.json.

usage: make_evidence.py <id> <tlc-log> <state-number> <edits-json> <exprs-json>
  edits-json: {"var": "TLA expression"} overrides applied to the extracted state
  exprs-json: [["label", "TLA expression over Old!/New!/U! instances"], ...]
The state is taken verbatim from a TLC error trace ("State N:" block).
"""
import json, os, re, subprocess, sys

BASE_VARS = ["up", "role", "phase", "leaderOf", "acceptedEpoch", "currentEpoch",
             "votes", "leadersByEpoch", "proposed", "queued", "appended", "durable",
             "committed", "applied", "snapshot", "recovered", "acked",
             "commitCertified", "messages", "syncMode", "syncSource", "syncJustified",
             "usedTxn", "rollbackAuthorized", "syncBuf", "syncCommit", "syncStage", "nlAcks"]
OLD_VARS = BASE_VARS[:24]

def extract(log, n):
    text = open(log).read()
    m = re.search(r"^State %d:.*?\n(.*?)(?=^State \d+:|\n\n|\Z)" % n, text, re.S | re.M)
    if not m:
        sys.exit("state %d not found in %s" % (n, log))
    body = m.group(1)
    parts = re.split(r"^/\\ ", body, flags=re.M)
    st = {}
    for p in parts:
        p = p.strip()
        if not p:
            continue
        k, v = p.split(" = ", 1)
        st[k.strip()] = " ".join(v.split())
    return st

def main():
    eid, log, n, edits, exprs = sys.argv[1], sys.argv[2], int(sys.argv[3]), json.loads(sys.argv[4]), json.loads(sys.argv[5])
    consts = json.loads(os.environ.get("EV_CONSTS", '{"Server": "{\\"s0\\", \\"s1\\", \\"s2\\"}", "Txn": "{0, 1, 2, 3, 4, 5, 6, 7, 1000}", "MaxEpoch": "3", "Nil": "\\"Nil\\""}'))
    st = extract(log, n)
    st.update(edits)
    for v in BASE_VARS:
        if v not in st:
            sys.exit("missing variable %s" % v)
    d = os.path.join(os.path.dirname(os.path.abspath(__file__)), eid)
    os.makedirs(d, exist_ok=True)
    rec = ",\n      ".join("%s |-> %s" % (v, st[v]) for v in BASE_VARS)
    sub_new = ", ".join("%s <- S0.%s" % (v, v) for v in BASE_VARS)
    sub_old = ", ".join("%s <- S0.%s" % (v, v) for v in OLD_VARS)
    exprs_tla = ",\n    ".join('<<"%s", %s>>' % (lbl, e) for lbl, e in exprs)
    mod = f"""---- MODULE {eid.replace('-', '_')} ----
\\* Generated by make_evidence.py from {os.path.relpath(log, d)} state {n}
\\* edits: {json.dumps(edits)}
EXTENDS TLC, Naturals, Sequences, FiniteSets
CONSTANTS Server, Txn, MaxEpoch, Nil
VARIABLE dummy
S0 == [{rec}]
Old == INSTANCE OldBase WITH {sub_old}
New == INSTANCE base WITH {sub_new}
U == INSTANCE Update WITH {sub_new}, counters <- [crash |-> 0, drop |-> 0, snapshot |-> 0], seen <- {{}}, everCommitted <- UNION {{{{S0.committed[s][k] : k \\in 1..Len(S0.committed[s])}} : s \\in Server}}, MaxCrash <- 0, MaxDrop <- 0, MaxSnapshot <- 0
Results == <<
    {exprs_tla}>>
ASSUME PrintT(Results)
Init == dummy = 0
Next == UNCHANGED dummy
====
"""
    name = eid.replace('-', '_')
    open(os.path.join(d, name + ".tla"), "w").write(mod)
    cfg = "INIT Init\nNEXT Next\nCONSTANTS\n" + "".join("    %s = %s\n" % (k, v) for k, v in consts.items())
    open(os.path.join(d, name + ".cfg"), "w").write(cfg)
    specdir = os.path.dirname(d)
    env = dict(os.environ)
    cp = "/work/lib/tla2tools.jar:/work/lib/CommunityModules-deps.jar"
    meta = "/dev/shm/specular-e2e-case-002/evidence-" + eid
    cmd = ["timeout", "300", "java", "-cp", cp, "-DTLA-Library=" + os.path.dirname(specdir), "tlc2.TLC",
           "-metadir", meta, "-config", name + ".cfg", name + ".tla"]
    # make base/Update/MC/OldBase resolvable
    for f in ["base.tla", "MC.tla", "Update.tla"]:
        src = os.path.join(os.path.dirname(specdir), f)
        dst = os.path.join(d, f)
        if os.path.lexists(dst): os.remove(dst)
        os.symlink(os.path.relpath(src, d), dst)
    dst = os.path.join(d, "OldBase.tla")
    if os.path.lexists(dst): os.remove(dst)
    os.symlink("../OldBase.tla", dst)
    r = subprocess.run(cmd, cwd=d, capture_output=True, text=True)
    subprocess.run(["rm", "-rf", meta])
    out = r.stdout + r.stderr
    open(os.path.join(d, "tlc.log"), "w").write("$ (cd spec/evidence/%s && %s)\n" % (eid, " ".join(cmd)) + out)
    res = [l for l in out.splitlines() if l.startswith("<<")]
    print(eid, "exit", r.returncode, res[:1])

main()
