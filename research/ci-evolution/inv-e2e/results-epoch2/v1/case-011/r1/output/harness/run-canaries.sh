#!/usr/bin/env bash
# Reachability canaries for the update Scenarios. Each canary invariant claims
# a Scenario state is unreachable; TLC must report it VIOLATED (the trace is
# the reachability witness). Pre-Vote is the only election path
# (TickPreVoteModes = {TRUE}, no operator trigger), three voters.
set -uo pipefail
suite_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
spec="$suite_root/spec"
canaries=(CanaryNoPreCandidate CanaryNoGrantedPreVoteResp
          CanaryNoRejectedPreVoteResp CanaryNoLeader CanaryNoLeaderWithPreCandidate
          CanaryNoFollowerLog CanaryNoPreCandidateCleared)
summary="$spec/output/canaries-summary.log"; : > "$summary"
for c in "${canaries[@]}"; do
  cfg="$spec/Canary_$c.cfg"
  cat > "$cfg" <<CFG
\* generated by harness/run-canaries.sh: expected VIOLATED (reachability witness)
SPECIFICATION MCSpec
CONSTANTS
    Server <- ReferenceServer
    NodeOrder <- ReferenceNodeOrder
    InitialConfig <- ReferenceInitialConfig
    MaxTerm = 2
    MaxLogIndex = 3
    TickPreVoteModes = {TRUE}
    MaxElectionCount = 2
    MaxExternalCount = 0
    MaxMembershipCount = 0
    MaxCrashCount = 0
    MaxRestartCount = 0
    MaxDropCount = 0
    MaxMessageCount = 6
CONSTRAINT MessageBound
VIEW ModelView
INVARIANTS
    $c
CFG
  SPECULA_MC_SECONDS=${SPECULA_MC_SECONDS:-600} SPECULA_MC_WORKERS=${SPECULA_MC_WORKERS:-4} SPECULA_MC_HEAP=${SPECULA_MC_HEAP:-8g} \
    "$suite_root/harness/run-model-check.sh" "canary-$c" Update "Canary_$c.cfg" | tee -a "$summary"
  depth=$(grep -cE '^State [0-9]+:' "$spec/output/mc-canary-$c.log")
  echo "  witness length: $depth states" | tee -a "$summary"
done
