"""Build spec/output/campaign-summary.md from run_tlc.sh logs."""
import glob, os, re
rows = []
for log in sorted(glob.glob('output/*.log')):
    txt = open(log, errors='replace').read()
    m = re.search(r'^# run=(\S+) module=(\S+) cfg=(\S+) budget=(\S+) workers=(\d+) extra=(.*?) start=(\S+)', txt, re.M)
    if not m:
        continue
    name, module, cfg, budget, workers, extra, start = m.groups()
    end = re.search(r'^# end=(\S+) rc=(\S+) outcome=(.*)$', txt, re.M)
    outcome = end.group(3) if end else 'RUNNING/INCOMPLETE'
    fin = re.findall(r'^(\d+) states generated, (\d+) distinct states found, (\d+) states left on queue', txt, re.M)
    prog = re.findall(r'^Progress\((\d+)\) at \S+ \S+: ([\d,]+) states generated .*?, ([\d,]+) distinct states found .*?, ([\d,]+) states left on queue', txt, re.M)
    sim = re.findall(r'^Progress: (\d+) states checked, (\d+) traces generated \(trace length: mean=(\d+)', txt, re.M)
    depth = re.findall(r'The depth of the complete state graph search is (\d+)', txt)
    if fin:
        g, d, q = fin[-1]; stats = f"{int(g):,} gen / {int(d):,} distinct / queue {int(q):,}"
        dep = depth[-1] if depth else (prog[-1][0] if prog else '?')
    elif prog:
        lv, g, d, q = prog[-1]; stats = f"last report: {g} gen / {d} distinct / queue {q}"; dep = lv
    elif sim:
        c, t, mean = sim[-1]; stats = f"simulation: {int(c):,} states, {int(t):,} traces, mean len {mean}"; dep = '-'
    else:
        stats = '-'; dep = depth[-1] if depth else '-'
    rows.append((os.path.basename(log)[:-4], module, cfg, budget, workers, extra.strip(), dep, stats, outcome))
with open('output/campaign-summary.md', 'w') as f:
    f.write('# Campaign summary (generated by spec/summarize_campaigns.py from spec/output/*.log)\n\n')
    f.write('Outcome classes: EXHAUSTED_NO_ERROR (state space exhausted under the cfg bounds); '
            'LIMITED_COVERAGE (planned budget reached; for BFS the queue was not exhausted, for -simulate runs the label text "queue not exhausted" only means the budget ended; no violation observed, not a proof); '
            'VIOLATION_OR_ERROR (counterexample in the log; classification in spec/bug-report.md / changelog). '
            'Reach_* and DischargeReach violations are expected reachability witnesses. Logs prefixed superseded-/precrashfix-/stopped are retained history, not final evidence. VIEW MCView (fault counters excluded) is inherited by MC.cfg, Update_*.cfg and inherited hunts: their EXHAUSTED/LIMITED results are with respect to counter-merged states.\n\n')
    f.write('| Log | Module | Cfg | Budget | Workers | Extra | Depth | Statistics | Outcome |\n|---|---|---|---|---|---|---|---|---|\n')
    for r in rows:
        f.write('| ' + ' | '.join(x.replace('|', '/') for x in r) + ' |\n')
print(open('output/campaign-summary.md').read())
