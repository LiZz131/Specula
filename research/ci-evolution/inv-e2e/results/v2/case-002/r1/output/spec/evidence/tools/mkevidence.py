#!/usr/bin/env python3
"""Generate a TLC evidence module from a state printed in a TLC log.

usage: mkevidence.py ID LOG STATE_INDEX OUTDIR --consts 'Server={...}' ...
       [--edit var=TLAEXPR] [--post LOG2 STATE2] [--old PROP ...] [--new PROP ...] [--step]
State/one-step evaluation of OldBase (prior suite) and UpdateProps (current) definitions.
"""
import argparse, os, re, sys

OLD_VARS = ["up","role","phase","leaderOf","acceptedEpoch","currentEpoch","votes",
            "leadersByEpoch","proposed","queued","appended","durable","committed",
            "applied","snapshot","recovered","acked","commitCertified","messages",
            "syncMode","syncSource","syncJustified","usedTxn","rollbackAuthorized"]
NEW_VARS = OLD_VARS + ["pendingSync","nlAckSent","nlAcks","certEpoch","memHist"]

def parse_state(log, idx):
    txt = open(log).read()
    m = re.search(r'^State %d: [^\n]*\n(.*?)(?=\n\s*\n|\nState \d+:|\Z)' % idx, txt, re.S | re.M)
    if not m:
        sys.exit("state %d not found in %s" % (idx, log))
    body = m.group(1)
    vals = {}
    for part in re.split(r'\n(?=/\\ )', body):
        part = part.strip()
        if not part.startswith('/\\ '):
            continue
        k, v = part[3:].split(' = ', 1)
        vals[k.strip()] = re.sub(r'\s+', ' ', v.strip())
    return vals

def rec(vals, names):
    return "[" + ",\n     ".join("%s |-> %s" % (n, vals[n]) for n in names) + "]"

ap = argparse.ArgumentParser()
ap.add_argument("id"); ap.add_argument("log"); ap.add_argument("idx", type=int); ap.add_argument("outdir")
ap.add_argument("--consts", nargs="+", required=True)
ap.add_argument("--edit", nargs="*", default=[])
ap.add_argument("--post", nargs=2)
ap.add_argument("--post-edit", nargs="*", default=[])
ap.add_argument("--old", nargs="*", default=[])
ap.add_argument("--new", nargs="*", default=[])
ap.add_argument("--modelvals", nargs="*", default=[])
ap.add_argument("--step", default=None, help="UpdateProps action predicate to check on PRE->POST")
a = ap.parse_args()
pre = parse_state(a.log, a.idx)
for e in a.edit:
    k, v = e.split("=", 1); pre[k] = v
os.makedirs(a.outdir, exist_ok=True)
mod = a.id
consts = [c.split("=", 1)[0].strip() for c in a.consts]
lines = ["---- MODULE %s ----" % mod,
         "\\* Generated by evidence/tools/mkevidence.py from %s state %d" % (os.path.relpath(a.log, a.outdir), a.idx),
         "EXTENDS Naturals, Integers, Sequences, FiniteSets, TLC",
         "CONSTANTS " + ", ".join(consts + a.modelvals)]
missing = [v for v in NEW_VARS if v not in pre]
if missing:
    sys.exit("missing vars: %s" % missing)
lines.append("S0 == " + rec(pre, NEW_VARS))
sub_old = ", ".join("%s <- S0.%s" % (v, v) for v in OLD_VARS)
sub_new = ", ".join("%s <- S0.%s" % (v, v) for v in NEW_VARS)
lines.append("Old == INSTANCE OldBase WITH " + sub_old)
lines.append("New == INSTANCE UpdateProps WITH " + sub_new)
if a.step:
    post = parse_state(a.post[0], int(a.post[1])) if a.post else dict(pre)
    for e in a.post_edit:
        k, v = e.split("=", 1); post[k] = v
    lines.append("S1 == " + rec(post, NEW_VARS))
    lines.append("VARIABLES " + ", ".join(NEW_VARS))
    lines.append("vars == <<" + ", ".join(NEW_VARS) + ">>")
    lines.append("P == INSTANCE UpdateProps")
    lines.append("Init == " + " /\\ ".join("%s = S0.%s" % (v, v) for v in NEW_VARS))
    lines.append("Next == " + " /\\ ".join("%s' = S1.%s" % (v, v) for v in NEW_VARS))
    lines.append("Spec == Init /\\ [][Next]_vars")
    lines.append("StepHolds == [][P!%s]_vars" % a.step)
else:
    lines.append("VARIABLE dummy")
    lines.append("Init == dummy = 0")
    lines.append("Next == UNCHANGED dummy")
    lines.append("Spec == Init /\\ [][Next]_dummy")
items = ['"%s"' % mod] + ['"old!%s"' % p for p in a.old for _ in [0]]
pr = ", ".join(['"%s"' % mod] + sum([['"old:%s"' % p, "Old!%s" % p] for p in a.old], []) +
               sum([['"new:%s"' % p, "New!%s" % p] for p in a.new], []))
lines.append("ASSUME PrintT(<<%s>>)" % pr)
lines.append("====")
open(os.path.join(a.outdir, mod + ".tla"), "w").write("\n".join(lines) + "\n")
cfg = ["SPECIFICATION Spec", "CONSTANTS"] + ["    " + c for c in a.consts] + ["    %s = %s" % (m, m) for m in a.modelvals] + ["CHECK_DEADLOCK FALSE"]
if a.step:
    cfg += ["PROPERTIES", "    StepHolds"]
open(os.path.join(a.outdir, mod + ".cfg"), "w").write("\n".join(cfg) + "\n")
print("wrote", os.path.join(a.outdir, mod + ".tla"))
