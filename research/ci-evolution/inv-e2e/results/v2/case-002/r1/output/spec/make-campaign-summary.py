#!/usr/bin/env python3
"""Build spec/output/update/campaign-summary.md from the run ledger and TLC logs."""
import json, re, os
root = "/work/current/.specula-output/spec"
ledger = os.path.join(root, "output/update/command-results.ndjson")
runs = {}
for line in open(ledger):
    r = json.loads(line)
    runs[r["id"]] = r            # last record per id wins
EXPECT = {
 "reachability": "expected violation (canary/witness)",
 "inherited-hunt": "expected violation (inherited canary)",
 "update-focused-bfs": "property check",
 "update-scenario-hunt": "property check",
 "update-old-control": "attribution control (old semantics)",
 "standard-mc-bfs": "standard convergence",
 "standard-base-bfs": "standard convergence (base Spec)",
 "update-full-bfs": "full update check (MCNext from MCInit)",
 "update-admission": "admission of focused findings (full MCNext)",
 "update-open-bfs": "open focused check (EnvUpdate)",
 "update-discharge": "discharge (omitted steps satisfy EnvUpdate)",
 "update-full-simulation": "simulation, depth 100",
 "standard-mc-simulation": "simulation, depth 100",
}
def info(r):
    log = os.path.join("/work/current/.specula-output", r["log"])
    txt = open(log, errors="replace").read() if os.path.exists(log) else ""
    m = re.search(r"Error: (Invariant \S+ is violated|Action property \S+ is violated|Temporal properties were violated|The behavior up to this point|Assumption[^\n]*|[^\n]*)", txt)
    viol = re.search(r"Error: (Invariant (\S+) is violated|Action property (\S+) is violated|Temporal properties were violated)", txt)
    cfg = re.search(r"-config (\S+)", txt)
    dur = re.findall(r"Finished in ([^\n]*?) at", txt)
    gen = re.findall(r"([\d,]+) states generated", txt)
    trc = len(re.findall(r"^State \d+:", txt, re.M))
    sim = "-simulate" in txt.split("\n")[0]
    budget = False
    secs = None
    if dur:
        d = dur[-1]
        mm = re.match(r"(?:(\d+)h )?(?:(\d+)min )?(\d+)s", d)
        if mm:
            secs = int(mm.group(1) or 0)*3600 + int(mm.group(2) or 0)*60 + int(mm.group(3))
            budget = secs >= 1700
    if viol:
        outcome = "VIOLATION: " + viol.group(1) + (" (trace %d states)" % trc if trc else "")
    elif r["completed_no_error"] and budget:
        outcome = "no violation; TimeBudget reached -> LIMITED_COVERAGE (not exhaustive)"
    elif r["completed_no_error"] and ("CONSTRAINT CanonicalDepthBound" in open(os.path.join(root, cfg.group(1))).read() if cfg else False):
        outcome = "no violation; exhausted within explicit depth bound (bounded)"
    elif r["completed_no_error"]:
        outcome = "no violation; state space exhausted (bounded constants)" if not sim else "no violation (simulation)"
    elif r["exit_code"] == 124:
        outcome = "no violation reported before the outer timeout -> LIMITED_COVERAGE (not exhaustive)"
    else:
        outcome = "ERROR rc=%s (see log)" % r["exit_code"]
    return cfg.group(1) if cfg else "?", outcome, (gen[-1] if gen else ""), dur[-1] if dur else ""
rows = []
for rid, r in runs.items():
    if not rid.startswith("final-") or r["kind"].startswith("trace"):
        continue
    cfg, outcome, gen, dur = info(r)
    dist, depth, q = r["distinct_states"], r["depth"], r["states_left_on_queue"]
    log = os.path.join("/work/current/.specula-output", r["log"])
    txt = open(log, errors="replace").read() if os.path.exists(log) else ""
    if r["exit_code"] == 124 or not re.search(r"states left on queue\.\n", txt):
        pm = re.findall(r"^Progress\((\d+)\) at ([^:]+:\d+:\d+): ([\d,]+) states generated.*?([\d,]+) distinct states found.*?([\d,]+) states left on queue", txt, re.M)
        if pm:
            depth, when, gen2, dist, q = pm[-1]
            dur = "outer timeout (last progress %s)" % when
    rows.append((r["kind"], rid, cfg, EXPECT.get(r["kind"], r["kind"]), dist, depth, q, dur, outcome, r["log"]))
rows.sort()
out = ["# Final model-checking campaign summary", "",
       "Generated by `spec/make-campaign-summary.py` from `spec/output/update/command-results.ndjson`.",
       "Every run: outer `timeout`, TLC states under `/dev/shm/specula-e2e-case-002/<id>` (removed after the run),",
       "`TimeBudget` constraint (~29 min). Budget-terminated runs are LIMITED_COVERAGE, never proofs.", "",
       "| kind | run | cfg | purpose | distinct | depth | queue | duration | outcome | log |",
       "|---|---|---|---|---:|---:|---:|---|---|---|"]
for k, rid, cfg, purpose, dist, depth, q, dur, outc, log in rows:
    out.append(f"| {k} | {rid} | `{cfg}` | {purpose} | {dist} | {depth} | {q} | {dur} | {outc} | `{log}` |")
trace_rows = [r for i, r in runs.items() if i.startswith("final-trace")]
out += ["", "## Final trace regression (stable candidate)", "",
        "| run | trace | outcome | depth |", "|---|---|---|---:|"]
for r in sorted(trace_rows, key=lambda x: x["id"]):
    out.append(f"| {r['id']} | `{r['trace']}` | {'pass (TraceMatched, 0 queued)' if r['completed_no_error'] else 'FAIL'} | {r['depth']} |")
open(os.path.join(root, "output/update/campaign-summary.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
