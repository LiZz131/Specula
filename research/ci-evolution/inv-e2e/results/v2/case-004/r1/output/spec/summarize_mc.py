#!/usr/bin/env python3
"""Summarize spec/output/mc-*.log into spec/output/model-checking-summary.md (facts only)."""
import glob, os, re, sys
out_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'output')
rows = []
for log in sorted(glob.glob(os.path.join(out_dir, 'mc-*.log'))):
    s = open(log, errors='replace').read()
    name = os.path.basename(log)[3:-4]
    cmd = re.search(r'^# cmd: (.*)$', s, re.M)
    viol = re.findall(r'Error: (Invariant \S+ is violated|Action property \S+ is violated|Temporal properties were violated|Evaluating invariant \S+ failed)', s)
    gen = re.findall(r'([\d,]+) states generated, ([\d,]+) distinct states found, ([\d,]+) states left on queue', s)
    depth = re.search(r'The depth of the complete state graph search is (\d+)', s)
    simdepth = re.findall(r'(\d+) states generated.*?\n?.*?traces generated', s)
    sim = 'simulate' in (cmd.group(1) if cmd else '')
    prog = re.findall(r'Progress\((\d+)\) at [^:]+:\d\d:\d\d: ([\d,]+) states generated \([^)]*\), ([\d,]+) distinct states found \([^)]*\), ([\d,]+) states left', s)
    done = 'Model checking completed. No error has been found.' in s
    stop = bool(re.search(r'stopAfter|TLC was stopped|Stopping|has been stopped', s))
    fin = re.search(r'# finished: (\S+) rc=(\d+)', s)
    if 'ABORTED manually' in s:
        status = 'ABORTED (reconfigured; not counted)'
    elif viol:
        status = 'VIOLATION: ' + '; '.join(sorted(set(viol)))
    elif done and not stop and gen and gen[-1][2] == '0':
        status = 'COMPLETE (queue empty) — no violation'
    elif fin:
        status = 'BUDGET-STOPPED (LIMITED_COVERAGE) — no violation' if not viol else status
    else:
        status = 'RUNNING/INCOMPLETE'
    states = gen[-1] if gen else (prog[-1][1:] if prog else ('?','?','?'))
    d = depth.group(1) if depth else (prog[-1][0] if prog else '?')
    simp = re.findall(r'Progress: ([\d]+) states checked, ([\d]+) traces generated \(trace length: mean=(\d+)', s)
    if sim:
        fin_s = re.search(r'The number of states generated: (\d+)', s)
        tr = re.search(r'Simulation using seed', s)
        if viol:
            status = 'SIMULATION VIOLATION: ' + '; '.join(sorted(set(viol)))
        elif fin:
            status = 'SIMULATION BUDGET-STOPPED (LIMITED_COVERAGE) — no violation'
        else:
            status = 'SIMULATION RUNNING'
        last = simp[-1] if simp else ('?','?','?')
        rows.append((name, (cmd.group(1).split(' ')[2] if cmd else '?'), status, last[0]+' states checked', last[1]+' traces', 'n/a', 'mean len '+last[2]+' (max 100)', fin.group(2) if fin else '-'))
        continue
    rows.append((name, (cmd.group(1).split(' ')[2] if cmd else '?'), status, states[0], states[1], states[2], d, fin.group(2) if fin else '-'))
with open(os.path.join(out_dir, 'model-checking-summary.md'), 'w') as f:
    f.write('# Model-checking run summary (generated by spec/summarize_mc.py)\n\n')
    f.write('| run | cfg | status | generated | distinct | queue | depth/diameter | rc |\n|---|---|---|---:|---:|---:|---:|---|\n')
    for r in rows:
        f.write('| %s | `%s` | %s | %s | %s | %s | %s | %s |\n' % r)
print(open(os.path.join(out_dir, 'model-checking-summary.md')).read())
