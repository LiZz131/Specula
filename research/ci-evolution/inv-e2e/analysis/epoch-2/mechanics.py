#!/usr/bin/env python3
"""Epoch-2 mechanics per run: tool use, TLC launch method, specular CLI, liveness proxies.

    INV_E2E_WORK=/mydata/bingzhuo/inv-e2e-epoch2 python3 analysis/epoch-2/mechanics.py > analysis/epoch-2/mechanics.md

Reads only each run's session log (WORK/attempts/<arm>/<case>/r<rep>/log/activity.jsonl) and its
exported output (results-epoch2/<arm>/<case>/r<rep>/output). No Gold.

Liveness proxies (definitions fixed in notes I-8):
  L1  a temporal property is defined in a non-Trace module (~>, <>, []<>, WF_/SF_ in a definition
      that a cfg PROPERTY/PROPERTIES names), excluding TraceConsumed-style trace properties;
  L2  a TLC log in output/spec/output names that property as checked (cfg referencing it was run);
  L3  get_tlc_summary returned violation_type temporal_property, or a log reports
      "Temporal propert(y|ies) .* violated".
"""
from __future__ import annotations

import json
import os
import re
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parents[2]
WORK = Path(os.environ.get("INV_E2E_WORK", "/mydata/bingzhuo/inv-e2e-epoch2"))
RESULTS = HERE / "results-epoch2"
TEMPORAL = re.compile(r"~>|<>|\[\]<>|\bWF_|\bSF_")


def session(path: Path) -> dict:
    names, calls, errors, cmds, summaries = {}, Counter(), Counter(), [], []
    for line in path.open(errors="replace"):
        try:
            ev = json.loads(line)
        except json.JSONDecodeError:
            continue
        if ev.get("type") == "assistant":
            for b in ev["message"].get("content") or []:
                if b.get("type") == "tool_use":
                    names[b["id"]] = b["name"]
                    calls[b["name"]] += 1
                    c = (b.get("input") or {}).get("command")
                    if isinstance(c, str):
                        cmds.append(c)
        elif ev.get("type") == "user" and isinstance(ev.get("message", {}).get("content"), list):
            for b in ev["message"]["content"]:
                if b.get("type") != "tool_result":
                    continue
                n = names.get(b.get("tool_use_id"), "")
                text = json.dumps(b.get("content"))
                if n.startswith("mcp__") and (b.get("is_error") or '\\"success\\": false' in text):
                    errors[n] += 1
                if n.endswith("get_tlc_summary"):
                    m = re.search(r'violation_type\\": \\"?(\w+)', text)
                    summaries.append(m.group(1) if m else "none")
    launch = Counter()
    for c in cmds:
        if "start_background.sh" in c:
            launch["start_background.sh"] += 1
        elif "run_model_check.sh" in c:
            launch["run_model_check.sh"] += 1
        elif re.search(r"tlc2\.TLC|tla2tools\.jar", c):
            launch["java tlc2 (own command)"] += 1
    launch["start_tlc (MCP)"] = calls.get("mcp__specular_tlc__start_tlc", 0)
    spec_cli = Counter(m.group(1) for c in cmds for m in re.finditer(r"(?:^|[;&|(\s])specular\s+([a-z-]+)", c))
    return {"mcp": {k.removeprefix("mcp__"): v for k, v in calls.items() if k.startswith("mcp__")},
            "mcp_errors": dict(errors), "tlc_launch": {k: v for k, v in launch.items() if v},
            "specular_cli": dict(spec_cli), "get_tlc_summary_types": dict(Counter(summaries))}


def liveness(out: Path) -> dict:
    spec = out / "spec"
    if not spec.is_dir():
        return {"L1": None}
    props: set[str] = set()
    for cfg in spec.glob("*.cfg"):
        if cfg.name.startswith("Trace"):
            continue
        text = cfg.read_text(errors="replace")
        for block in re.findall(r"^PROPERT(?:Y|IES)\s+((?:\s*\w+\s*)+)", text, re.M):
            props.update(w for w in block.split() if w not in ("INVARIANT", "INVARIANTS", "CONSTANT", "CONSTANTS"))
    temporal = set()
    for tla in spec.glob("*.tla"):
        if tla.name.startswith("Trace") or "TTrace" in tla.name:
            continue
        for name, body in re.findall(r"^(\w+)\s*==\s*(.*?)(?=^\w+\s*==|\Z)", tla.read_text(errors="replace"), re.M | re.S):
            if name in props and TEMPORAL.search(body):
                temporal.add(name)
    logs = list((spec / "output").glob("**/*.log")) if (spec / "output").is_dir() else []
    checked = {p for p in temporal for lg in logs if p in lg.read_text(errors="replace")[:200000]}
    # Trace validation reports a rejected trace as a violated TraceConsumed-style property; only
    # violations of a named non-trace property count.
    violated = []
    for lg in logs:
        for name in re.findall(r"Temporal property (\w+) was violated", lg.read_text(errors="replace")):
            if name in temporal:
                violated.append(f"{lg.name}:{name}")
    return {"L1": sorted(temporal), "L2": sorted(checked), "L3_logs": violated[:5]}


def main() -> None:
    print("# Epoch-2 mechanics per run\n\nGenerated by `analysis/epoch-2/mechanics.py`. Session logs and exported outputs only; no Gold.\n")
    rows = []
    for rj in sorted(RESULTS.glob("v*/case-*/r*/run.json")):
        arm, case, rep = rj.parts[-4], rj.parts[-3], rj.parts[-2]
        log = WORK / "attempts" / arm / case / rep / "log/activity.jsonl"
        s = session(log) if log.is_file() else {}
        lv = liveness(rj.parent / "output")
        run = json.loads(rj.read_text())
        rows.append((arm, case, rep, run.get("layout", "specula"), s, lv))
    print("| run | layout | MCP calls | MCP errors | TLC launch | specular CLI | get_tlc_summary types | L1 | L2 | L3 |")
    print("|---|---|---|---|---|---|---|---|---|---|")
    for arm, case, rep, layout, s, lv in rows:
        fmt = lambda d: ", ".join(f"{k} {v}" for k, v in sorted((d or {}).items())) or "-"
        print(f"| {arm}/{case}/{rep} | {layout} | {fmt(s.get('mcp'))} | {fmt(s.get('mcp_errors'))} | "
              f"{fmt(s.get('tlc_launch'))} | {fmt(s.get('specular_cli'))} | {fmt(s.get('get_tlc_summary_types'))} | "
              f"{', '.join(lv.get('L1') or []) or '-'} | {', '.join(lv.get('L2') or []) or '-'} | "
              f"{', '.join(lv.get('L3_logs') or []) or '-'} |")


if __name__ == "__main__":
    main()
